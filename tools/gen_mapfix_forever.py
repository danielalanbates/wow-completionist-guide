"""Write CompletionRoute/Data/MapFix_forever.lua: the zone maps whose world rectangle changed between Classic Era
and WoW Forever (wago.tools UiMapAssignment, via tools/maps_era.lua and tools/maps_forever.lua from tools/gen_maps.py).

    python3 tools/gen_mapfix_forever.py

Forever runs the era data (guides, inns, transit, roads, dungeon doors), all written as map percentages on the Era
maps.  Where Forever reshaped a map (Mulgore, Eastern Plaguelands, Redridge Mountains, Stormwind City on build
1.60.1.70790) the same percentage is a different place, so the addon converts era percentages through world
coordinates onto the Forever map (Core/Util.lua U.EraToForever).  Maps that only changed parent or type are left out.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RE = re.compile(r'^\s*\[(\d+)\] = \{ "((?:[^"\\]|\\.)*)", (-?\d+), ([-\d.]+), ([-\d.]+), ([-\d.]+), ([-\d.]+), (\d+), (\d+) \}')


def load(fl):
    out, build = {}, None
    for ln in (ROOT / "tools" / f"maps_{fl}.lua").read_text(encoding="utf-8").splitlines():
        m = re.search(r"build (\d+(?:\.\d+)+)", ln)
        if m and build is None:
            build = m.group(1)
        m = RE.match(ln)
        if m:
            out[int(m.group(1))] = (m.group(2), int(m.group(3))) + tuple(float(m.group(i)) for i in range(4, 8))
    return out, build


def main():
    era, eb = load("era")
    fv, fb = load("forever")
    rows = []
    for mid in sorted(set(era) & set(fv)):
        a, b = era[mid], fv[mid]
        if a[1] != b[1]:
            continue  # different continent: not a reshape, skip
        if max(abs(x - y) for x, y in zip(a[2:], b[2:])) < 0.5:
            continue
        rows.append(f'    [{mid}] = {{ {a[2]:.2f}, {a[3]:.2f}, {a[4]:.2f}, {a[5]:.2f}, {b[2]:.2f}, {b[3]:.2f}, {b[4]:.2f}, {b[5]:.2f} }}, '
                    f'-- {b[0]}')
    out = ROOT / "CompletionRoute" / "Data" / "MapFix_forever.lua"
    out.write_text("\n".join([
        f"-- GENERATED by tools/gen_mapfix_forever.py from wago.tools UiMapAssignment (era {eb}, forever {fb}). Do not edit.",
        "-- [uiMapID] = { eraTopX, eraLeftY, eraWidth, eraHeight, foreverTopX, foreverLeftY, foreverWidth, foreverHeight }",
        "-- world: wx = topX - y01 * height, wy = leftY - x01 * width (tools/gen_maps.py convention)",
        "local _, NS = ...",
        "NS.ForeverMapFix = {",
        *rows,
        "}",
        "",
    ]), encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(rows)} reshaped maps")


if __name__ == "__main__":
    main()
